#!/usr/bin/env python3
"""Generate Mintlify MDX pages for the built-in types and prelude.

Source of truth: the `.g` declaration files under <gust>/stdlib/builtins and
<gust>/stdlib/prelude — bodyless doc-stubs (`def string`, `def list.append`, …)
that are not part of any compiled program.

Outputs:
  - docs/builtins/prelude.mdx         (prelude funcs + standard error types)
  - docs/builtins/<type>.mdx          (one per builtin type: string, integer, list, ...)

This is the builtins/prelude half of the reference. The importable stdlib
package pages (docs/stdlib/*.mdx) and the index are generated by the Gust
autodoc/inspect pipeline (the compiler's own introspection) instead of
re-parsing `.g` text. Those doc-stubs live outside any compiled program, so
compile-time `inspect` cannot see them — that is why they remain here.

Normally run via scripts/gen_docs.sh, the single entrypoint that regenerates
the whole reference and invokes this script as its final pass. To regenerate
only the builtins/prelude pages, run it directly:

Run:  python3 scripts/gen_api_docs.py            (auto-detects ../gust)
      GUST_ROOT=/path/to/gust python3 scripts/gen_api_docs.py

Edit the `.g` docstrings, not the generated `.mdx`.
"""

import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DOCS = os.path.dirname(HERE)
GUST = os.environ.get("GUST_ROOT") or os.path.normpath(os.path.join(DOCS, "..", "gust"))
STDLIB = os.path.join(GUST, "stdlib")

# ── source model ──────────────────────────────────────────────────────────────


class Decl:
    def __init__(self, kind, name, sig=None, doc="", section=None):
        self.kind = kind  # function | method | struct | error | enum | constant
        self.name = name  # e.g. "now_ms", "DateTime.to", "ValueError"
        self.sig = sig  # display signature, e.g. "now_ms() → integer"
        self.doc = doc.strip()
        self.section = section  # nearest "# ── Section ──" divider
        self.fields = []  # struct fields: list of "name: type"
        self.variants = []  # enum variants
        self.ctype = None  # constant type
        self.cval = None  # constant value
        self.methods = []  # struct: attached methods (filled at render)


DIVIDER = re.compile(r"^#\s*[─-]+\s*(.+?)\s*[─-]+\s*$")
DEF = re.compile(r"^def\s+(foreign\s+)?(!?)(.+?)\s*$")
METHOD = re.compile(r"^([A-Za-z_]\w*)\.(__?\w+|\w+)\s*\((.*)\)\s*(?:->\s*(.+))?$")
FUNC = re.compile(r"^(!?)([a-z_]\w*)\s*\((.*)\)\s*(?:->\s*(.+))?$")
STRUCT = re.compile(r"^([A-Za-z_]\w*)\s*$")  # `def Value` or builtin `def string`
ERROR = re.compile(r"^error\s+([A-Z]\w*)\s*\((.*)\)\s*$")
ENUM = re.compile(r"^(auto_enum|enum)\s+([A-Z]\w*)\s*(?::\s*(\w+))?\s*$")
CONST = re.compile(r"^([A-Z][A-Z0-9_]*)\s*:\s*constant\[(.+?)\]\s*=\s*(.+?)\s*$")
FIELD = re.compile(r"^\s*([a-z_]\w*)\s*:\s*(.+?)\s*$")


def render_prose(text):
    """Render a docstring / module-doc into MDX. A ```` ``` ```` fence passes its
    region through verbatim (tagged `gust` when bare); an indented run outside any
    fence is lifted into a fenced `gust` block, dedented by the run's own minimum
    indent so column alignment (e.g. a two-column reference table) is preserved; a
    lone hanging-indent wrap line stays prose; everything else is JSX-escaped prose."""
    if not text:
        return ""
    lines = text.split("\n")
    out, i, n = [], 0, len(lines)
    in_fence = False
    while i < n:
        line = lines[i]
        t = line.strip()
        if t.startswith("```"):
            out.append("```gust" if (t == "```" and not in_fence) else t)
            in_fence = not in_fence
            i += 1
        elif in_fence:
            out.append(line)
            i += 1
        elif t and line.startswith(" "):
            run = []
            while i < n and (lines[i].startswith(" ") or not lines[i].strip()):
                if not lines[i].strip():
                    if i + 1 < n and lines[i + 1].startswith(" "):
                        run.append("")
                        i += 1
                        continue
                    break
                run.append(lines[i])
                i += 1
            while run and not run[-1].strip():
                run.pop()
            indents = [len(r) - len(r.lstrip(" ")) for r in run if r.strip()]
            base = min(indents) if indents else 0
            code = [r[base:] if len(r) >= base else r.strip() for r in run]
            if len([c for c in code if c.strip()]) >= 2:
                out += ["", "```gust"] + code + ["```", ""]
            else:  # a lone hanging-indent wrap line — keep as prose
                for c in code:
                    out.append(mdx_safe(c.strip()))
        else:
            out.append(mdx_safe(line))
            i += 1
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()


def arrow(ret):
    return f" → {ret.strip()}" if ret else ""


def read_docstring(lines, i):
    """If lines[i:] (skipping blanks) starts a triple-quoted docstring, return
    (text, index_after). Otherwise ('', i)."""
    j = i
    while j < len(lines) and lines[j].strip() == "":
        j += 1
    if j >= len(lines):
        return "", i
    s = lines[j].lstrip()
    if not s.startswith('"""'):
        return "", i
    body = s[3:]
    if body.rstrip().endswith('"""') and len(body.rstrip()) >= 3:  # single-line
        return body.rstrip()[:-3].strip(), j + 1
    out = [body]
    j += 1
    while j < len(lines):
        if '"""' in lines[j]:
            out.append(lines[j][: lines[j].index('"""')])
            j += 1
            break
        out.append(lines[j])
        j += 1
    # Dedent continuation lines by their common leading whitespace, so relative
    # indentation (e.g. an indented code example) is preserved, not flattened.
    first = out[0].strip()
    cont = out[1:]
    indents = [len(l) - len(l.lstrip()) for l in cont if l.strip()]
    base = min(indents) if indents else 0
    dedented = [first] + [
        l[base:].rstrip() if len(l) >= base else l.rstrip() for l in cont
    ]
    return "\n".join(dedented).strip(), j


def parse_file(path):
    lines = open(path).read().split("\n")
    decls = []
    section = None
    pending = []  # accumulated leading '#' comment lines (non-divider)
    module_doc = []
    header_done = False  # past the file's leading copyright + module-doc block?
    i = 0
    n = len(lines)
    while i < n:
        raw = lines[i]
        line = raw.rstrip()
        stripped = line.strip()

        # ── file header: copyright line + leading module-doc comment block ──
        if not header_done:
            if stripped.startswith("#") and "Copyright" in stripped:
                i += 1
                continue  # drop the license header
            if DIVIDER.match(stripped):
                header_done = True  # a divider ends the header
            elif stripped.startswith("#"):
                mc = re.match(r"^#( ?)(.*)$", line)  # preserve indentation after '# '
                content = mc.group(2) if mc else ""
                if not re.match(r"^Gust (standard library|prelude)\s*[—-]", content):
                    module_doc.append(content)  # "" for blank-comment lines
                i += 1
                continue
            elif stripped == "":
                if module_doc:
                    header_done = True  # blank after module doc ends it
                i += 1
                continue
            else:
                header_done = True  # first real declaration

        m = DIVIDER.match(stripped)
        if m:
            section = m.group(1).strip()
            pending = []
            i += 1
            continue

        if stripped.startswith("#"):
            pending.append(stripped.lstrip("#").strip())
            i += 1
            continue

        if stripped == "":
            i += 1
            continue

        # ── constant ──
        m = CONST.match(stripped)
        if m:
            d = Decl("constant", m.group(1), section=section)
            d.ctype, d.cval = m.group(2), m.group(3)
            d.doc = "\n".join(pending).strip()
            decls.append(d)
            pending = []
            i += 1
            continue

        # ── error ──
        m = ERROR.match(stripped)
        if m:
            d = Decl(
                "error", m.group(1), sig=f"{m.group(1)}({m.group(2)})", section=section
            )
            doc, i2 = read_docstring(lines, i + 1)
            d.doc = doc or "\n".join(pending).strip()
            decls.append(d)
            pending = []
            i = i2 if doc else i + 1
            continue

        # ── enum ──
        m = ENUM.match(stripped)
        if m:
            d = Decl("enum", m.group(2), section=section)
            base = m.group(3)
            d.sig = f"{m.group(1)} {m.group(2)}" + (f": {base}" if base else "")
            doc, i2 = read_docstring(lines, i + 1)
            d.doc = doc or "\n".join(pending).strip()
            i = i2 if doc else i + 1
            # variants until 'end'
            while i < n and lines[i].strip() != "end":
                v = lines[i].strip()
                if v and not v.startswith("#"):
                    d.variants.append(v)
                i += 1
            decls.append(d)
            pending = []
            i += 1
            continue

        # ── def (struct | function | method) ──
        m = DEF.match(stripped)
        if m:
            _, bang, rest = m.group(1), m.group(2), m.group(3)
            mm = METHOD.match(rest)
            ms = STRUCT.match(rest)
            mf = FUNC.match(rest)
            if ms:  # struct definition
                d = Decl("struct", ms.group(1), sig=ms.group(1), section=section)
                doc, i2 = read_docstring(lines, i + 1)
                d.doc = doc or "\n".join(pending).strip()
                i = i2 if doc else i + 1
                while i < n and lines[i].strip() != "end":
                    fm = FIELD.match(lines[i])
                    if fm and not lines[i].strip().startswith("#"):
                        d.fields.append(f"{fm.group(1)}: {fm.group(2)}")
                    i += 1
                decls.append(d)
                pending = []
                i += 1
                continue
            elif mm:  # Type.method
                typ, name, params, ret = mm.groups()
                bang_s = "!" if bang else ""
                d = Decl(
                    "method",
                    f"{typ}.{name}",
                    sig=f"{typ}.{name}{bang_s}({params}){arrow(ret)}",
                    section=section,
                )
            elif mf:  # free function
                _, name, params, ret = mf.groups()
                bang_s = "!" if bang else ""
                d = Decl(
                    "function",
                    name,
                    sig=f"{name}{bang_s}({params}){arrow(ret)}",
                    section=section,
                )
            else:
                i += 1
                continue
            doc, i2 = read_docstring(lines, i + 1)
            d.doc = doc or "\n".join(pending).strip()
            decls.append(d)
            pending = []
            i = i2 if doc else i + 1
            continue

        # any other code line: stop swallowing comments, move on
        pending = []
        i += 1

    return decls, "\n".join(module_doc).strip("\n")


def parse_package(pkg_dir):
    """Parse every .g in a package dir; merge decls. The module doc comes from the
    file named <pkg>.g (the package's main decl file), else the first found."""
    pkg = os.path.basename(pkg_dir)
    decls, doc = [], ""
    for path in sorted(glob.glob(os.path.join(pkg_dir, "*.g"))):
        d, md = parse_file(path)
        decls.extend(d)
        if md and (not doc or os.path.basename(path) == f"{pkg}.g"):
            doc = md
    return decls, doc


# ── rendering ────────────────────────────────────────────────────────────────


def mdx_safe(text):
    """Escape <, {, } that fall OUTSIDE inline `code` spans, so MDX doesn't try to
    parse them as JSX. Docstrings are plain prose — none of these are intentional JSX."""
    if not text:
        return text
    parts = re.split(r"(`[^`]*`)", text)
    for k in range(0, len(parts), 2):  # even indices = non-code segments
        parts[k] = (
            parts[k].replace("<", "&lt;").replace("{", "&#123;").replace("}", "&#125;")
        )
    return "".join(parts)


def parse_doc_section(doc, headers):
    """Split a docstring into prose `body` and a named section (e.g. `Arguments:`
    / `Fields:`). Mirrors autodoc/mdx.g's `parse_doc_section`: inside the section
    each `name: description` line is one entry, ending at the first blank or
    non-`name:` line; the section is lifted out of the body. Returns (body, {name:
    desc})."""
    if not doc:
        return doc, {}
    headers = {h.lower() for h in headers}
    lines = doc.split("\n")
    entries, body = {}, []
    i, n = 0, len(lines)
    while i < n:
        if lines[i].strip().lower() in headers:
            i += 1
            while i < n:
                entry = lines[i].strip()
                if not entry:
                    i += 1
                    break
                ci = entry.find(": ")
                if ci < 0:
                    break
                entries[entry[:ci].strip()] = entry[ci + 2 :].strip()
                i += 1
        else:
            body.append(lines[i])
            i += 1
    return "\n".join(body).strip(), entries


def code_sig(d):
    """The Gust source spelling of a declaration for a fenced code block:
    `def name(...) -> ret` for callables, `error Name(...)` for error types
    (the parsed `→` arrow is downgraded to the `->` the source uses)."""
    if d.kind == "error":
        return f"error {d.sig}"
    return "def " + d.sig.replace(" → ", " -> ")


def split_params(sig):
    """The `name: type` parameter strings parsed from a signature, splitting on
    top-level commas only (so `dict[K, V]` stays intact)."""
    i = sig.find("(")
    if i < 0:
        return []
    depth, inner = 0, []
    for c in sig[i:]:
        if c in "([{":
            depth += 1
            if depth == 1:
                continue
        elif c in ")]}":
            depth -= 1
            if depth == 0:
                break
        inner.append(c)
    raw = "".join(inner)
    parts, cur, depth = [], "", 0
    for c in raw:
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        if c == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += c
    if cur.strip():
        parts.append(cur.strip())
    return parts


LIST_SECTIONS = {
    "arguments:": "args",
    "args:": "args",
    "parameters:": "args",
    "fields:": "fields",
    "variants:": "variants",
    "members:": "variants",
    "raises:": "raises",
    "throws:": "raises",
}
PROSE_SECTIONS = {
    "returns:": "returns",
    "return:": "returns",
    "examples:": "examples",
    "example:": "examples",
    "note:": "note",
    "notes:": "note",
    "warning:": "warning",
    "warnings:": "warning",
}


def _dedent_block(lines):
    """Join `lines` after stripping the smallest leading-space indent common to
    their non-blank members, so a section body indented under its header renders
    flush. Mirrors autodoc/mdx.g's `_strip_common_indent`."""
    indents = [len(l) - len(l.lstrip(" ")) for l in lines if l.strip()]
    base = min(indents) if indents else 0
    return "\n".join(l[base:] if len(l) >= base else l.strip() for l in lines).strip()


def parse_sections(doc):
    """Split a docstring into prose `body` plus every recognized section, mirroring
    autodoc/mdx.g's `parse_sections`. List sections (`Arguments:` / `Fields:` /
    `Variants:` / `Raises:`) become ordered `(name, desc)` pairs; prose sections
    (`Returns:` / `Examples:` / `Note:` / `Warning:`) capture their block. All
    recognized sections are lifted out of `body`. Returns `(body, sections)` where
    `sections` maps a canonical kind to a list of pairs or a prose string."""
    if not doc:
        return doc, {}
    lines = doc.split("\n")
    body, sections = [], {}
    i, n = 0, len(lines)
    while i < n:
        head = lines[i].strip().lower()
        if head in LIST_SECTIONS:
            kind = LIST_SECTIONS[head]
            entries = sections.setdefault(kind, [])
            i += 1
            entry_indent = None
            while i < n:
                raw = lines[i]
                if not raw.strip():
                    i += 1
                    break
                ind = len(raw) - len(raw.lstrip(" "))
                entry = raw.strip()
                if entry_indent is not None and ind > entry_indent and entries:
                    name, desc = entries[-1]
                    entries[-1] = (name, (desc + " " + entry).strip())
                    i += 1
                    continue
                ci = entry.find(": ")
                if ci < 0:
                    break
                if entry_indent is None:
                    entry_indent = ind
                entries.append((entry[:ci].strip(), entry[ci + 2 :].strip()))
                i += 1
        elif head in PROSE_SECTIONS:
            kind = PROSE_SECTIONS[head]
            i += 1
            block = []
            while i < n and lines[i].strip().lower() not in LIST_SECTIONS and (
                lines[i].strip().lower() not in PROSE_SECTIONS
            ):
                block.append(lines[i])
                i += 1
            sections[kind] = _dedent_block(block)
        else:
            body.append(lines[i])
            i += 1
    return "\n".join(body).strip(), sections


def render_section_tail(sections):
    """Render the prose / relationship sections shared across declaration kinds —
    Returns, Raises, Examples, and Note / Warning callouts — matching the order and
    formatting of autodoc/mdx.g's `_render_sections_tail`."""
    out = []
    if sections.get("returns"):
        out += ["**Returns**", "", render_prose(sections["returns"]), ""]
    raises = sections.get("raises", [])
    if raises:
        out += ["**Raises**", ""]
        for name, desc in raises:
            out.append(f"- `{name}` — {mdx_safe(desc)}" if desc else f"- `{name}`")
        out.append("")
    ex = sections.get("examples")
    if ex:
        out += ["**Examples**", ""]
        if "```" in ex:
            out.append(render_prose(ex))
        else:
            out += ["```gust", ex, "```"]
        out.append("")
    for tag in ("note", "warning"):
        content = sections.get(tag)
        if content:
            comp = "Note" if tag == "note" else "Warning"
            out += [f"<{comp}>", render_prose(content), f"</{comp}>", ""]
    return out


def render_decl(d, anchor_prefix=""):
    """Render one declaration the way autodoc/mdx.g does: an anchor, the
    signature as a fenced `gust` code block, the docstring prose, a **Parameters**
    list pairing each parameter's type with its `Arguments:` description, and the
    trailing **Returns** / **Raises** / **Examples** / callout sections."""
    out = []
    anc = (anchor_prefix + d.name) if anchor_prefix and "." not in d.name else d.name
    body, sections = parse_sections(d.doc)
    argdocs = dict(sections.get("args", []))
    out.append(f'<a id="{anc}" />')
    out += ["```gust", code_sig(d), "```", ""]
    if body:
        out.append(render_prose(body))
        out.append("")
    params = split_params(d.sig)
    if argdocs and params and d.kind in ("function", "method"):
        out += ["**Parameters**", ""]
        for p in params:
            name = p.split(":")[0].strip()
            desc = argdocs.get(name, "")
            out.append(f"- `{p}` — {mdx_safe(desc)}" if desc else f"- `{p}`")
        out.append("")
    out += render_section_tail(sections)
    return out


def render_group(decls, anchor_prefix="", level=3):
    """Render a list of function/method decls, sub-grouped by their section, with
    a `---` rule between consecutive entries (not right after a section heading)."""
    out = []
    head = "#" * level
    last_section = "___none___"
    first_in_section = True
    for d in decls:
        if d.section and d.section != last_section:
            out.append(f"{head} {d.section}")
            out.append("")
            last_section = d.section
            first_in_section = True
        if not first_in_section:
            out += ["---", ""]
        out.extend(render_decl(d, anchor_prefix))
        first_in_section = False
    return out


def attach_methods(decls):
    """Group methods under their owning struct; return (structs, free_funcs)."""
    structs = {d.name: d for d in decls if d.kind == "struct"}
    free = []
    for d in decls:
        if d.kind == "method":
            owner = d.name.split(".")[0]
            if owner in structs:
                structs[owner].methods.append(d)
            else:
                free.append(d)  # method on a type with no struct decl here
        elif d.kind == "function":
            free.append(d)
    return structs, free


def render_constants(consts):
    """Render constants as section-grouped tables. A leading `#` comment becomes
    the Description cell; a `| ` in the value/desc is escaped for the table."""
    out = ["## Constants", ""]
    any_doc = any(c.doc for c in consts)
    last_section = "___start___"
    for c in consts:
        sec = c.section
        if sec != last_section:
            if last_section != "___start___":
                out.append("")
            if sec:
                out.append(f"### {sec}")
                out.append("")
            cols = (
                "| Name | Type | Value | Description |"
                if any_doc
                else "| Name | Type | Value |"
            )
            sep = (
                "|------|------|-------|-------------|"
                if any_doc
                else "|------|------|-------|"
            )
            out += [cols, sep]
            last_section = sec
        val = c.cval.replace("|", "\\|")
        if any_doc:
            desc = mdx_safe((c.doc or "").replace("\n", " ")).replace("|", "\\|")
            out.append(f"| `{c.name}` | `{c.ctype}` | `{val}` | {desc} |")
        else:
            out.append(f"| `{c.name}` | `{c.ctype}` | `{val}` |")
    out.append("")
    return out


def render_fields(fields, fielddocs):
    """A **Fields** list, each `name: type` paired with its `Fields:`-block
    description when present."""
    out = ["**Fields**", ""]
    for f in fields:
        name = f.split(":")[0].strip()
        desc = fielddocs.get(name, "")
        out.append(f"- `{f}` — {mdx_safe(desc)}" if desc else f"- `{f}`")
    out.append("")
    return out


def render_struct(s):
    out = [f"## `{s.name}`", ""]
    body, fielddocs = parse_doc_section(s.doc, ["fields:"])
    if body:
        out.append(render_prose(body))
        out.append("")
    if s.fields:
        out += render_fields(s.fields, fielddocs)
    if s.methods:
        out += render_group(s.methods)
    return out


def page_header(title, desc, use_pkg=None):
    out = [
        "---",
        f"title: {title}",
        f'description: "{desc.replace(chr(34), chr(39))}"'
        if desc
        else "description: Gust standard library reference",
        "---",
        "",
    ]
    if use_pkg:
        out += ["```gust", f"use {use_pkg}", "```", ""]
    return out


def first_sentence(text, fallback):
    if not text:
        return fallback
    t = text.strip().split("\n")[0]
    m = re.split(r"(?<=[.!?])\s", t, 1)
    return m[0].strip().rstrip(".") or fallback


def render_package_page(pkg, decls, module_doc):
    desc = first_sentence(module_doc, f"The {pkg} standard library package")
    out = page_header(pkg, desc, use_pkg=pkg)
    if module_doc:
        out.append(render_prose(module_doc))
        out.append("")
    consts = [d for d in decls if d.kind == "constant"]
    enums = [d for d in decls if d.kind == "enum"]
    errs = [d for d in decls if d.kind == "error"]
    structs, free = attach_methods(decls)
    if consts:
        out += render_constants(consts)
    if enums:
        for e in enums:
            out += [f"## `{e.name}`", "", f'<a id="{e.name}" />', f"**`{e.sig}`**", ""]
            if e.doc:
                out.append(render_prose(e.doc))
                out.append("")
            out.append("**Variants**")
            out.append("")
            for v in e.variants:
                out.append(f"- `{v}`")
            out.append("")
    # structs in source order
    for d in decls:
        if d.kind == "struct":
            out += render_struct(structs[d.name])
    if free:
        out += ["## Functions", ""]
        out += render_group(free, anchor_prefix=f"{pkg}.")
    if errs:
        out += ["## Errors", ""]
        for e in errs:
            out += render_decl(e)
    return "\n".join(out).rstrip() + "\n"


TYPE_DESC = {
    "string": "The built-in string type — an immutable sequence of characters — and its methods",
    "integer": "The built-in 64-bit signed integer type and its methods",
    "float": "The built-in double-precision float type and its methods",
    "bool": "The built-in boolean type and its methods",
    "list": "The built-in list[T] type and its methods",
    "dict": "The built-in dict[K, V] type and its methods",
    "none": "The built-in none (unit) type and its methods",
    "bytes": "The built-in bytes type — a mutable sequence of raw octets — and its methods",
    "tuple": "The built-in tuple type — a fixed-length group of differently typed values — and its methods",
    "ref": "The built-in ref[T] type — a refcounted, shared, mutable cell — and its members",
    "struct": "Structs (def Name) — their fields, the __dict conversion, and reflection properties",
    "enum": "Enums (enum Name) — their members and reflection properties",
    "function": "Functions (def name) — the reflection properties on a function name",
}


def render_type_page(tname, decls):
    """One page per built-in type; method sections (Case, Search, …) become ## headings."""
    struct = next((d for d in decls if d.kind == "struct" and d.name == tname), None)
    methods = [d for d in decls if d.kind == "method" and d.name.split(".")[0] == tname]
    body, sections = parse_sections(struct.doc) if struct and struct.doc else ("", {})
    fielddocs = dict(sections.get("fields", []))
    desc = first_sentence(body, TYPE_DESC[tname]) if body else TYPE_DESC[tname]
    out = page_header(tname, desc)
    if body:
        out.append(render_prose(body))
        out.append("")
    if struct and struct.fields:
        out += ["## Fields", ""]
        for f in struct.fields:
            name = f.split(":")[0].strip()
            fdesc = fielddocs.get(name, "")
            out.append(f"- `{f}` — {mdx_safe(fdesc)}" if fdesc else f"- `{f}`")
        out.append("")
    out += render_section_tail(sections)
    out += render_group(methods, level=2)
    return "\n".join(out).rstrip() + "\n"


def render_prelude_page(prelude_decls):
    out = page_header("Prelude", "Functions auto-imported into every program")
    out += [
        "The prelude is loaded into every program automatically — no `use` required. "
        "It provides a handful of global functions; the standard error types live on "
        "the [Errors](/builtins/errors) page.",
        "",
    ]
    pfuncs = [d for d in prelude_decls if d.kind == "function"]
    if pfuncs:
        out += ["## Functions", ""]
        out += render_group(pfuncs, level=3)
    return "\n".join(out).rstrip() + "\n"


def render_errors_page(error_decls):
    """The standard error types on their own page, each as a fenced `error …`
    code block — the prelude page links here."""
    out = page_header(
        "Errors",
        "The standard error types, available in every program without an import",
    )
    out += [
        "The standard error types are part of the prelude — available everywhere with "
        "no `use`.\n"
        "```gust\n"
        'raise ValueError(message: "...") # Raise the error\n'
        "try\n"
        "    ...\n"
        "catch ValueError as e # Catch the error (as e is optional)\n"
        "    ...\n"
        "end\n```",
        "",
    ]
    for i, e in enumerate(error_decls):
        if i > 0:
            out += ["---", ""]
        out += render_decl(e)
    return "\n".join(out).rstrip() + "\n"


# ── main ─────────────────────────────────────────────────────────────────────


def main():
    if not os.path.isdir(STDLIB):
        sys.exit(f"stdlib not found at {STDLIB} (set GUST_ROOT)")
    out_dir = os.path.join(DOCS, "stdlib")
    os.makedirs(out_dir, exist_ok=True)

    written = []
    # builtins: one page per type + a prelude page, under docs/builtins/
    bi_dir = os.path.join(DOCS, "builtins")
    os.makedirs(bi_dir, exist_ok=True)
    BUILTIN_TYPES = [
        "string",
        "integer",
        "float",
        "bool",
        "list",
        "dict",
        "none",
        "bytes",
        "tuple",
        "ref",
        "struct",
        "enum",
        "function",
    ]
    prelude_decls = []
    for f in sorted(glob.glob(os.path.join(STDLIB, "prelude", "*.g"))):
        prelude_decls.extend(parse_file(f)[0])
    open(os.path.join(bi_dir, "prelude.mdx"), "w").write(
        render_prelude_page(prelude_decls)
    )
    written.append("builtins/prelude")
    perrs = [d for d in prelude_decls if d.kind == "error"]
    if perrs:
        open(os.path.join(bi_dir, "errors.mdx"), "w").write(render_errors_page(perrs))
        written.append("builtins/errors")
    for t in BUILTIN_TYPES:
        d, _ = parse_file(os.path.join(STDLIB, "builtins", f"{t}.g"))
        open(os.path.join(bi_dir, f"{t}.mdx"), "w").write(render_type_page(t, d))
        written.append(f"builtins/{t}")

    # NOTE: the importable-package pages (docs/stdlib/**/*.mdx) and the stdlib
    # index are generated by the Gust autodoc/inspect pipeline driven from
    # gen_docs.sh — it reads the compiler's parsed program instead of re-parsing
    # `.g` text here. This script is kept only for the built-in *type* pages and
    # the prelude, which are bodyless doc-stubs that live outside any compiled
    # program, so compile-time `inspect` can't reach them.

    print(f"generated {len(written)} builtin/prelude pages from {STDLIB}")
    for w in written:
        print("  ", w)
    print("\n(stdlib package pages + index come from scripts/gen_docs.sh)")


if __name__ == "__main__":
    main()
